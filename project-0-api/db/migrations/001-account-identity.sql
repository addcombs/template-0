BEGIN;

CREATE SCHEMA IF NOT EXISTS admin;

CREATE TABLE IF NOT EXISTS admin.users (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email        varchar(255),
    first_name   varchar(255),
    last_name    varchar(255),
    phone_number varchar(255),
    cognito_sub  varchar(255),
    create_date  timestamptz,
    update_date  timestamptz,
    create_user  varchar(255),
    update_user  varchar(255)
);

ALTER TABLE admin.users ADD COLUMN IF NOT EXISTS cognito_sub varchar(255);

CREATE UNIQUE INDEX IF NOT EXISTS users_cognito_sub_key ON admin.users (cognito_sub);
CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_key ON admin.users (lower(email));

COMMIT;
